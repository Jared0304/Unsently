-- Unsently reference schema (SQLite)
--
-- The server creates this schema automatically at startup. This file documents
-- the storage model and can also be used to initialize a database manually.
--
-- Security model:
--   * There is no users table and no public account identity.
--   * The browser holds a random owner token in an HttpOnly cookie.
--   * owner_hash stores only SHA-256(token). The raw token never enters SQLite.
--   * Ownership checks happen in the API layer. SQLite has no row-level
--     security, so never expose this database through the web server.
--   * The public note serializer omits owner_hash.

PRAGMA journal_mode = WAL;
PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS notes (
  id             TEXT PRIMARY KEY,           -- UUID generated by the server
  text           TEXT NOT NULL DEFAULT '',   -- note body, max 5000 chars
  sender_name    TEXT,                       -- optional, max 80 chars
  recipient_name TEXT,                       -- optional, max 80 chars
  image_file     TEXT,                       -- generated WebP filename only
  music_json     TEXT,                       -- validated iTunes preview metadata
  paper          TEXT NOT NULL DEFAULT 'cream',
  ink            TEXT NOT NULL DEFAULT 'ink',
  font           TEXT NOT NULL DEFAULT 'hand',
  doodle         TEXT NOT NULL DEFAULT 'star',
  owner_hash     TEXT NOT NULL,              -- SHA-256 owner token hash
  created_at     TEXT NOT NULL,              -- ISO-8601 UTC
  updated_at     TEXT NOT NULL               -- ISO-8601 UTC
);

CREATE INDEX IF NOT EXISTS notes_created_at_idx
  ON notes (created_at DESC);

CREATE INDEX IF NOT EXISTS notes_owner_hash_idx
  ON notes (owner_hash);

-- A single About row. owner_hash starts NULL (unclaimed) and is set to the
-- first browser that successfully saves the page. After that, only that owner
-- hash may update it. image_file is a generated WebP filename.
CREATE TABLE IF NOT EXISTS about (
  id         INTEGER PRIMARY KEY CHECK (id = 1),
  text       TEXT NOT NULL DEFAULT '',
  image_file TEXT,
  owner_hash TEXT,
  updated_at TEXT NOT NULL
);

-- Seed the neutral default About text. The application also performs this
